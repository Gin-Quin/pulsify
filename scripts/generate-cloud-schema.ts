// Writes the PostgreSQL schema embedded by the Unikraft Cloud Rust server.
import { UNIKRAFT_CLOUD_POSTGRES_SCHEMA } from "../packages/cloud-server/unikraft-cloud/source/index.ts";

const target = new URL(
	"../packages/cloud-server/unikraft-cloud/server/sql/schema.sql",
	import.meta.url,
);
await Bun.write(
	target,
	`-- Generated by scripts/generate-cloud-schema.ts. Do not edit.\n${UNIKRAFT_CLOUD_POSTGRES_SCHEMA}`,
);
console.log(target.pathname);
